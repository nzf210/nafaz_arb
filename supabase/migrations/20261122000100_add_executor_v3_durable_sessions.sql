-- Executor V3 PR-01B: additive durable session/leg identity and aggregate event stream.
-- Legacy rows intentionally retain NULL provenance/fencing/typed-market metadata.
-- Do not infer or backfill ambiguous identities from pair_key or owner_fencing.

ALTER TABLE public.execution_sessions
    ADD COLUMN IF NOT EXISTS admission_key TEXT,
    ADD COLUMN IF NOT EXISTS source_dispatch_id TEXT,
    ADD COLUMN IF NOT EXISTS account_scope_id TEXT,
    ADD COLUMN IF NOT EXISTS state_version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS aggregate_version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS fencing_generation BIGINT,
    ADD COLUMN IF NOT EXISTS policy_snapshot JSONB,
    ADD COLUMN IF NOT EXISTS policy_snapshot_hash TEXT,
    ADD COLUMN IF NOT EXISTS execution_policy_snapshot JSONB,
    ADD COLUMN IF NOT EXISTS risk_policy_snapshot JSONB,
    ADD COLUMN IF NOT EXISTS exit_policy_snapshot JSONB;

ALTER TABLE public.execution_legs
    ADD COLUMN IF NOT EXISTS account_scope_id TEXT,
    ADD COLUMN IF NOT EXISTS normalized_symbol TEXT,
    ADD COLUMN IF NOT EXISTS base_asset TEXT,
    ADD COLUMN IF NOT EXISTS quote_asset TEXT,
    ADD COLUMN IF NOT EXISTS settlement_asset TEXT,
    ADD COLUMN IF NOT EXISTS contract_type TEXT,
    ADD COLUMN IF NOT EXISTS contract_size NUMERIC(38,18),
    ADD COLUMN IF NOT EXISTS position_side TEXT,
    ADD COLUMN IF NOT EXISTS quantity_unit TEXT,
    ADD COLUMN IF NOT EXISTS base_per_unit NUMERIC(38,18),
    ADD COLUMN IF NOT EXISTS order_quantity NUMERIC(38,18),
    ADD COLUMN IF NOT EXISTS exposure_quantity NUMERIC(38,18),
    ADD COLUMN IF NOT EXISTS state_version BIGINT NOT NULL DEFAULT 0;

DO $$
DECLARE
    fk_name TEXT;
BEGIN
    -- Discover the actual FK name from the catalog; never assume the name
    -- generated by the original migration. Preserve the relationship while
    -- changing destructive cascade semantics to evidence-preserving RESTRICT.
    FOR fk_name IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'public.execution_legs'::regclass
          AND confrelid = 'public.execution_sessions'::regclass
          AND contype = 'f'
    LOOP
        EXECUTE format(
            'ALTER TABLE public.execution_legs DROP CONSTRAINT %I',
            fk_name
        );
    END LOOP;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.execution_legs'::regclass
          AND conname = 'execution_legs_session_id_fkey'
    ) THEN
        ALTER TABLE public.execution_legs
            ADD CONSTRAINT execution_legs_session_id_fkey
            FOREIGN KEY (session_id)
            REFERENCES public.execution_sessions(session_id)
            ON DELETE RESTRICT;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_execution_sessions_admission_key
    ON public.execution_sessions (admission_key)
    WHERE admission_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_execution_sessions_account_state
    ON public.execution_sessions (account_scope_id, status, updated_at DESC);

CREATE INDEX IF NOT EXISTS idx_execution_legs_session_state
    ON public.execution_legs (session_id, status, updated_at DESC);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.execution_sessions'::regclass
          AND conname = 'execution_sessions_versions_nonnegative'
    ) THEN
        ALTER TABLE public.execution_sessions
            ADD CONSTRAINT execution_sessions_versions_nonnegative
            CHECK (state_version >= 0 AND aggregate_version >= 0) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.execution_legs'::regclass
          AND conname = 'execution_legs_state_version_nonnegative'
    ) THEN
        ALTER TABLE public.execution_legs
            ADD CONSTRAINT execution_legs_state_version_nonnegative
            CHECK (state_version >= 0) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.execution_legs'::regclass
          AND conname = 'execution_legs_typed_quantity_positive'
    ) THEN
        ALTER TABLE public.execution_legs
            ADD CONSTRAINT execution_legs_typed_quantity_positive
            CHECK (
                (contract_size IS NULL OR contract_size > 0)
                AND (base_per_unit IS NULL OR base_per_unit > 0)
                AND (order_quantity IS NULL OR order_quantity >= 0)
                AND (exposure_quantity IS NULL OR exposure_quantity >= 0)
            ) NOT VALID;
    END IF;
END $$;

ALTER TABLE public.execution_sessions
    VALIDATE CONSTRAINT execution_sessions_versions_nonnegative;
ALTER TABLE public.execution_legs
    VALIDATE CONSTRAINT execution_legs_state_version_nonnegative;
ALTER TABLE public.execution_legs
    VALIDATE CONSTRAINT execution_legs_typed_quantity_positive;

CREATE TABLE IF NOT EXISTS public.execution_session_events (
    event_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id TEXT NOT NULL
        REFERENCES public.execution_sessions(session_id) ON DELETE RESTRICT,
    aggregate_version BIGINT NOT NULL CHECK (aggregate_version > 0),
    entity_type TEXT NOT NULL CHECK (entity_type IN ('SESSION', 'LEG')),
    entity_id TEXT NOT NULL,
    entity_version BIGINT NOT NULL CHECK (entity_version > 0),
    event_type TEXT NOT NULL,
    event_idempotency_key TEXT,
    actor_id TEXT NOT NULL,
    fencing_generation BIGINT,
    correlation_id TEXT,
    reason TEXT,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_execution_session_events_aggregate_version
        UNIQUE (session_id, aggregate_version)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_execution_session_events_idempotency
    ON public.execution_session_events (session_id, event_idempotency_key)
    WHERE event_idempotency_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_execution_session_events_timeline
    ON public.execution_session_events (session_id, aggregate_version DESC);

CREATE OR REPLACE FUNCTION public.reject_execution_session_event_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'execution_session_events is append-only';
END;
$$;

DROP TRIGGER IF EXISTS trg_execution_session_events_append_only
    ON public.execution_session_events;
CREATE TRIGGER trg_execution_session_events_append_only
    BEFORE UPDATE OR DELETE ON public.execution_session_events
    FOR EACH ROW EXECUTE FUNCTION public.reject_execution_session_event_mutation();

ALTER TABLE public.execution_session_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.execution_session_events FROM anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.execution_session_events TO service_role;

COMMENT ON COLUMN public.execution_sessions.fencing_generation IS
    'V3 numeric ownership generation. NULL is preserved for legacy sessions whose ownership cannot be proven.';
COMMENT ON COLUMN public.execution_sessions.aggregate_version IS
    'Monotonic per-session event cursor; increment atomically with every accepted aggregate event.';
COMMENT ON TABLE public.execution_session_events IS
    'Append-only durable execution aggregate event stream. Session row and event must be committed in one transaction.';
